<?php

namespace App\Services\Physio\Demo;

/**
 * Curated 50-case catalog for graduation demo mode (PHYSIO_DEMO_MODE).
 * Deterministic markers: [PHYS-XX] in symptoms and CASE:PHYS-XX in additional_information.
 */
final class PhysioDemoCaseCatalog
{
    /** @var list<array<string, mixed>>|null */
    private ?array $cases = null;

    /** @return list<array<string, mixed>> */
    public function all(): array
    {
        return $this->cases();
    }

    /** @return array<string, mixed>|null */
    public function byId(int $id): ?array
    {
        foreach ($this->cases() as $case) {
            if ($case['id'] === $id) {
                return $case;
            }
        }

        return null;
    }

    /** @return list<array<string, mixed>> */
    public function canonicalInputs(): array
    {
        $inputs = [];
        foreach ($this->cases() as $case) {
            $inputs[] = $case['input'];
        }

        return $inputs;
    }

    /** @return list<array<string, mixed>> */
    private function cases(): array
    {
        if ($this->cases === null) {
            $this->cases = $this->buildCases();
        }

        return $this->cases;
    }

    /** @return list<array<string, mixed>> */
    private function buildCases(): array
    {
        $built = [];
        foreach ($this->definitions() as $definition) {
            $built[] = $this->makeCase($definition);
        }

        return $built;
    }

    /**
     * @param  array<string, mixed>  $definition
     * @return array<string, mixed>
     */
    private function makeCase(array $definition): array
    {
        $id = (int) $definition['id'];
        $caseId = sprintf('PHYS-%02d', $id);
        $input = $definition['input'];
        $input['body_area'] = $definition['body_area'];
        $input['symptoms'] = '['.$caseId.'] '.$input['symptoms'];
        $input['additional_information'] = trim(
            ($input['additional_information'] ?? '').' CASE:'.$caseId
        );

        $exercises = $definition['recommended_exercises'];
        $dosageParts = [];
        foreach ($exercises as $ex) {
            if (! is_array($ex)) {
                continue;
            }
            $dosageParts[] = trim(sprintf(
                '%s: %s × %s',
                (string) ($ex['name'] ?? 'Exercise'),
                (string) ($ex['sets'] ?? '—'),
                (string) ($ex['reps_or_duration'] ?? '—'),
            ));
        }

        return [
            'id' => $id,
            'case_id' => $caseId,
            'body_area' => $definition['body_area'],
            'body_region' => $definition['body_area'],
            'symptoms' => $input['symptoms'],
            'pain_score' => $input['pain_level'] ?? null,
            'pain_level' => $input['pain_level'] ?? null,
            'duration' => $input['duration'] ?? null,
            'onset' => $input['onset'] ?? null,
            'cause' => $input['trigger'] ?? null,
            'trigger' => $input['trigger'] ?? null,
            'activity' => $input['activity'] ?? null,
            'additional_information' => $input['additional_information'] ?? null,
            'expected_clinical_pattern' => $definition['expected_clinical_pattern'],
            'confidence' => $definition['confidence'],
            'escalation_level' => $definition['escalation_level'],
            'input' => $input,
            'key_findings' => $definition['key_findings'],
            'initial_clinical_impression' => $definition['initial_clinical_impression'],
            'clinical_assessment' => 'Initial clinical assessment based on the information provided.',
            'recommended_exercises' => $exercises,
            'exercise_dosage' => $dosageParts === []
                ? 'No exercise program until medically cleared.'
                : implode('; ', $dosageParts),
            'activity_advice' => $definition['activity_advice'],
            'avoid' => $definition['avoid'],
            'what_to_avoid' => $definition['avoid'],
            'red_flags' => $definition['red_flags'],
            'next_step' => $definition['next_step'],
            'follow_up' => $definition['next_step'],
            'evidence_basis' => $definition['evidence_basis'],
        ];
    }

    /**
     * @return list<array<string, mixed>>
     */
    private function ex(
        string $name,
        string $purpose,
        string $sets,
        string $repsOrDuration,
        string $rest = '30–60 seconds between sets',
        string $intensity = 'Low to moderate, pain-free range',
        string $progression = 'Increase volume gradually as symptoms allow',
        ?string $caution = null,
    ): array {
        return [[
            'name' => $name,
            'purpose' => $purpose,
            'sets' => $sets,
            'reps_or_duration' => $repsOrDuration,
            'rest' => $rest,
            'intensity' => $intensity,
            'progression' => $progression,
            'caution' => $caution,
        ]];
    }

    /**
     * @param  list<array<string, mixed>>  $items
     * @return list<array<string, mixed>>
     */
    private function mergeEx(array ...$items): array
    {
        return array_merge(...$items);
    }

    /** @return list<array<string, mixed>> */
    private function definitions(): array
    {
        return array_merge(
            $this->neckCases(),
            $this->lowerBackCases(),
            $this->shoulderCases(),
            $this->kneeCases(),
            $this->ankleFootCases(),
            $this->hipCases(),
            $this->otherMusculoskeletalCases(),
            $this->redFlagCases(),
        );
    }

